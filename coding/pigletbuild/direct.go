package pigletbuild

import (
	"fmt"
	"go/build"
	"os"
	"path/filepath"
	"strings"

	"golang.org/x/mod/modfile"

	"github.com/MichaelKinsy/PiG/coding/extension/host/runtimecell"
	"github.com/MichaelKinsy/PiG/coding/extension/host/subprocess"
)

const directFactory = "DirectExtension"

// pig additive (D234): direct selections resolve an exact Go package without consulting the SDK factory scanner. The generated assignment type-checks its native factory against the host being built.
func resolveDirectConfig(name, path string) (subprocess.ExtConfig, error) {
	path, err := filepath.Abs(path)
	if err != nil {
		return subprocess.ExtConfig{}, err
	}
	pkg, err := build.Default.ImportDir(path, 0)
	if err != nil {
		return subprocess.ExtConfig{}, fmt.Errorf("direct member must select one Go package: %w", err)
	}
	if pkg.Name == "main" {
		return subprocess.ExtConfig{}, fmt.Errorf("direct member cannot be a standalone main package")
	}
	root := path
	for {
		if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
			break
		}
		parent := filepath.Dir(root)
		if parent == root {
			return subprocess.ExtConfig{}, fmt.Errorf("direct member has no containing Go module")
		}
		root = parent
	}
	file, err := readModFile(root)
	if err != nil || file.Module == nil {
		return subprocess.ExtConfig{}, fmt.Errorf("direct member %s has no module path", root)
	}
	rel, err := filepath.Rel(root, path)
	if err != nil {
		return subprocess.ExtConfig{}, err
	}
	packagePath := file.Module.Mod.Path
	if rel != "." {
		packagePath += "/" + filepath.ToSlash(rel)
	}
	cfg := subprocess.ExtConfig{Name: name, Source: root, Enabled: true, RuntimeLanguage: "go", EntrypointKind: "factory", ModulePath: file.Module.Mod.Path, Package: packagePath, Factory: directFactory}
	for dir := root; ; dir = filepath.Dir(dir) {
		workPath := filepath.Join(dir, "go.work")
		data, err := os.ReadFile(workPath)
		if err == nil {
			work, err := modfile.ParseWork(workPath, data, nil)
			if err != nil {
				return subprocess.ExtConfig{}, err
			}
			for _, use := range work.Use {
				member := use.Path
				if !filepath.IsAbs(member) {
					member = filepath.Join(dir, member)
				}
				module, err := readModFile(member)
				if err != nil {
					return subprocess.ExtConfig{}, err
				}
				if module.Module == nil {
					return subprocess.ExtConfig{}, fmt.Errorf("workspace member %s has no module path", member)
				}
				// Host modules come from the PiG source being built, never from a member's workspace.
				if module.Module.Mod.Path == "github.com/MichaelKinsy/PiG" || strings.HasPrefix(module.Module.Mod.Path, "github.com/MichaelKinsy/PiG/extensions/sdk") {
					continue
				}
				cfg.GoWorkspaceModules = append(cfg.GoWorkspaceModules, filepath.Clean(member))
			}
			break
		}
		if !os.IsNotExist(err) {
			return subprocess.ExtConfig{}, err
		}
		if filepath.Dir(dir) == dir {
			break
		}
	}
	return cfg, nil
}

func collectDirect(cell subprocess.CellSpec) ([]fusedEntry, error) {
	var entries []fusedEntry
	for _, cfg := range cell.Extensions {
		if cfg.RuntimeLanguage != "go" || cfg.Factory != directFactory || cfg.Source == "" || cfg.Package == "" {
			return nil, fmt.Errorf("direct member %q must supply a Go package and %s", cfg.Name, directFactory)
		}
		entries = append(entries, fusedEntry{Name: cfg.Name, Pkg: runtimecell.ExtPackageName(cfg.Name), Factory: directFactory, Root: cfg.Source, ModulePath: cfg.ModulePath, Package: cfg.Package, WorkspaceModules: cfg.GoWorkspaceModules, Direct: true})
	}
	return entries, nil
}

func renderDirectRegistry(entries []fusedEntry) string {
	var b strings.Builder
	b.WriteString("// Code generated by pig piglet build. DO NOT EDIT.\npackage main\n\nimport (\n\t\"github.com/MichaelKinsy/PiG/coding/extension\"\n")
	for _, entry := range entries {
		_, _ = fmt.Fprintf(&b, "\t%s %q\n", entry.Pkg, entry.Package)
	}
	b.WriteString(")\n\nfunc directFactories() []extension.NamedInlineExtension {\n\treturn []extension.NamedInlineExtension{\n")
	for _, entry := range entries {
		_, _ = fmt.Fprintf(&b, "\t\textension.NamedInlineExtension{Name: %q, Factory: %s.%s},\n", entry.Name, entry.Pkg, entry.Factory)
	}
	b.WriteString("\t}\n}\n")
	return b.String()
}
